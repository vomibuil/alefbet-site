def base_letter(s):
    for ch in s or "":
        if "א" <= ch <= "ת":
            return ch
    return ""

FINAL_TO_BASE = {"ך": "כ", "ם": "מ", "ן": "נ", "ף": "פ", "ץ": "צ"}

def page(idx, slovar_by_letter):
    he, final, slug, name, name_he, sound, gematria, about = LETTERS[idx]
    title = f"Буква {name.lower()} ({he}) — алфавит иврита: произношение и примеры | AlefBet"
    desc = f"Буква иврита {name.lower()} {he}: как читается ({sound}), гематрия {gematria}, примеры слов с произношением. Алфавит иврита по буквам."

    facts = f"""<div class="al-facts">
        <div class="al-fact"><span class="al-fact-label">Звук</span><span class="al-fact-value">{esc(sound)}</span></div>
        <div class="al-fact"><span class="al-fact-label">Номер в алфавите</span><span class="al-fact-value">{idx + 1} из 22</span></div>
        <div class="al-fact"><span class="al-fact-label">Гематрия</span><span class="al-fact-value">{gematria}</span></div>
        {f'<div class="al-fact"><span class="al-fact-label">Конечная форма</span><span class="al-fact-value" lang="he" dir="rtl">{final}</span></div>' if final else ''}
      </div>"""

    examples = slovar_by_letter.get(he, [])[:8]
    ex_block = ""
    if examples:
        links = "".join(
            f'<li><a href="../slovar/{s}.html"><span lang="he" dir="rtl">{esc(w["he"])}</span> {esc(first_ru(w["ru"]))}</a></li>'
            for s, w in examples)
